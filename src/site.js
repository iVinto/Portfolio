/* vinto.work — v2 behaviour.
   Pages are static HTML generated by tools/build.mjs; this script only enhances them:
   theme toggle, header state, Index filters/sort/preview and the Photos-like viewer. */
(() => {
  "use strict";
  const root = document.documentElement;
  const reduceMotion = matchMedia("(prefers-reduced-motion: reduce)");

  /* ---------- theme: White / Black, remembered ---------- */
  const THEME_KEY = "vinto-theme";
  const systemDark = matchMedia("(prefers-color-scheme: dark)");
  const effectiveTheme = () => root.dataset.theme || (systemDark.matches ? "dark" : "light");
  const syncThemeButtons = () => {
    for (const b of document.querySelectorAll("[data-theme-set]")) {
      b.setAttribute("aria-pressed", String(b.dataset.themeSet === effectiveTheme()));
    }
  };
  document.addEventListener("click", e => {
    const b = e.target.closest("[data-theme-set]");
    if (!b) return;
    root.dataset.theme = b.dataset.themeSet;
    try { localStorage.setItem(THEME_KEY, b.dataset.themeSet); } catch (_) { /* private mode */ }
    syncThemeButtons();
  });
  systemDark.addEventListener?.("change", syncThemeButtons);
  syncThemeButtons();

  /* ---------- header turns to glass once the page scrolls ---------- */
  let ticking = false;
  const onScroll = () => {
    if (ticking) return;
    ticking = true;
    requestAnimationFrame(() => { root.classList.toggle("is-scrolled", window.scrollY > 8); ticking = false; });
  };
  addEventListener("scroll", onScroll, { passive: true });
  onScroll();

  initIndex();
  initViewer();

  /* ---------- Index: filters, sorting, hover preview ---------- */
  function initIndex() {
    const list = document.querySelector(".i-rows");
    if (!list) return;
    const rows = [...list.querySelectorAll(".row")];
    const countEl = document.querySelector(".i-count");

    // Filters: groups are exclusive inside (Festival vs Concert), combined across (AND).
    const active = new Map();
    const fbtns = [...document.querySelectorAll(".filters button")];
    for (const b of fbtns) {
      b.addEventListener("click", () => {
        const { tag, group } = b.dataset;
        if (!tag) active.clear();
        else if (active.get(group) === tag) active.delete(group);
        else active.set(group, tag);
        for (const x of fbtns) {
          x.setAttribute("aria-pressed", String(x.dataset.tag ? active.get(x.dataset.group) === x.dataset.tag : active.size === 0));
        }
        const tags = [...active.values()];
        let shown = 0;
        for (const r of rows) {
          const has = r.dataset.tags.split(" ");
          r.hidden = !tags.every(t => has.includes(t));
          if (!r.hidden) shown++;
        }
        if (countEl) countEl.textContent = `${shown} ${shown === 1 ? "event" : "events"}`;
      });
    }

    // Sorting by column; numbers default to descending, text to ascending.
    const heads = [...document.querySelectorAll(".i-head [data-sort]")];
    let sortKey = "year", dir = -1;
    for (const h of heads) {
      h.addEventListener("click", () => {
        const k = h.dataset.sort;
        const numeric = k === "year" || k === "count";
        if (k === sortKey) dir = -dir; else { sortKey = k; dir = numeric ? -1 : 1; }
        const val = r => numeric ? Number(r.dataset[k]) : r.dataset[k];
        rows.sort((a, b) => {
          const va = val(a), vb = val(b);
          const c = numeric ? va - vb : String(va).localeCompare(String(vb));
          return c * dir || Number(a.dataset.order) - Number(b.dataset.order);
        });
        for (const r of rows) list.appendChild(r);
        for (const x of heads) x.setAttribute("aria-sort", x === h ? (dir > 0 ? "ascending" : "descending") : "none");
      });
    }

    // Desktop: the hovered row shows its photo in a fixed place, with a cross-fade.
    const pv = document.querySelector(".i-preview");
    if (!pv || !matchMedia("(hover: hover)").matches) return;
    const imgs = pv.querySelectorAll(".i-ph img");
    const title = pv.querySelector("b"), meta = pv.querySelector("figcaption span");
    let front = 0, current = null, token = 0;
    const show = r => {
      if (current === r) return;
      current = r;
      title.textContent = r.dataset.name;
      meta.textContent = r.dataset.meta;
      const next = imgs[front ^ 1], mine = ++token;
      next.srcset = r.dataset.pvSrcset;
      next.src = r.dataset.pvSrc;
      const swap = () => {
        if (mine !== token) return;
        next.classList.add("on");
        imgs[front].classList.remove("on");
        front ^= 1;
      };
      (next.decode ? next.decode() : Promise.resolve()).then(swap, swap);
    };
    for (const r of rows) {
      r.addEventListener("pointerenter", () => show(r));
      r.addEventListener("focus", () => show(r));
    }
  }

  /* ---------- Viewer: opens from the thumbnail, swipes 1:1, drag down to close ---------- */
  function initViewer() {
    const dataEl = document.getElementById("photos");
    const dlg = document.querySelector("dialog.viewer");
    if (!dataEl || !dlg) return;
    const thumbs = [...document.querySelectorAll("a[data-i]")];
    // The Selected grid is shuffled on every visit, so the viewer follows the order of the thumbnails on screen.
    const data = JSON.parse(dataEl.textContent);
    const photos = thumbs.length === data.length ? thumbs.map(a => data[Number(a.dataset.i)]) : data;
    if (photos !== data) thumbs.forEach((a, k) => { a.dataset.i = k; });
    const track = dlg.querySelector(".v-track");
    const film = dlg.querySelector(".v-film");
    const countEl = dlg.querySelector(".v-count");
    const eventEl = dlg.querySelector(".v-event");
    const captionEl = dlg.querySelector(".v-caption");
    const prevBtn = dlg.querySelector(".v-prev"), nextBtn = dlg.querySelector(".v-next");
    const toast = dlg.querySelector(".v-toast");
    const canMorph = () => typeof document.startViewTransition === "function" && !reduceMotion.matches;
    let built = false, index = 0, isOpen = false;

    const slideImg = i => track.children[i]?.querySelector("img");
    const thumbImg = i => thumbs.find(a => Number(a.dataset.i) === i)?.querySelector("img");
    const width = () => track.clientWidth || window.innerWidth;

    function build() {
      if (built) return;
      built = true;
      photos.forEach((p, i) => {
        const fig = document.createElement("figure");
        fig.className = "v-slide";
        const img = new Image(p.w, p.h);
        img.alt = p.alt;
        img.decoding = "async";
        img.loading = "lazy";
        img.draggable = false;
        img.sizes = "100vw";
        img.srcset = p.srcset;
        img.src = p.src;
        img.style.backgroundImage = `url("${p.ph}")`;
        fig.append(img);
        track.append(fig);
        const b = document.createElement("button");
        b.type = "button";
        b.setAttribute("aria-label", `Photo ${i + 1}`);
        const t = new Image();
        t.alt = "";
        t.loading = "lazy";
        t.src = p.thumb;
        b.append(t);
        b.addEventListener("click", () => go(i));
        film.append(b);
      });
    }

    function render(i) {
      index = i;
      const p = photos[i];
      countEl.textContent = `${i + 1} / ${photos.length}`;
      if (eventEl) {
        eventEl.textContent = p.event;
        if (eventEl.tagName === "A") eventEl.href = p.href;
      }
      if (captionEl) captionEl.textContent = [p.event, p.date].filter(Boolean).join(" · ");
      if (prevBtn) prevBtn.disabled = i === 0;
      if (nextBtn) nextBtn.disabled = i === photos.length - 1;
      [...film.children].forEach((b, k) => b.setAttribute("aria-current", String(k === i)));
      const active = film.children[i];
      if (active) film.scrollTo({ left: active.offsetLeft - film.clientWidth / 2 + active.offsetWidth / 2, behavior: reduceMotion.matches ? "auto" : "smooth" });
      for (const k of [i - 1, i, i + 1]) { const im = slideImg(k); if (im) im.loading = "eager"; }
      if (isOpen) history.replaceState(history.state, "", `#${i + 1}`);
    }

    function go(i, smooth = true) {
      i = Math.max(0, Math.min(photos.length - 1, i));
      track.scrollTo({ left: i * width(), behavior: smooth && !reduceMotion.matches ? "smooth" : "instant" });
      if (!smooth) render(i);
    }

    // Index follows the native scroll-snap position (1:1 finger tracking and momentum are the browser's).
    let settle;
    const syncFromScroll = () => {
      const i = Math.round(track.scrollLeft / width());
      if (i !== index && i >= 0 && i < photos.length) render(i);
    };
    track.addEventListener("scroll", () => { clearTimeout(settle); settle = setTimeout(syncFromScroll, 80); }, { passive: true });
    track.addEventListener("scrollend", syncFromScroll);
    addEventListener("resize", () => { if (isOpen) track.scrollLeft = index * width(); });

    const wait = ms => new Promise(r => setTimeout(r, ms));

    async function open(i, { from = null, push = true } = {}) {
      build();
      if (push) history.pushState({ viewer: true }, "", `#${i + 1}`);
      const target = slideImg(i);
      target.loading = "eager";
      // Give the large image a moment so the morph lands on pixels, not on an empty box.
      await Promise.race([target.decode().catch(() => {}), wait(350)]);
      const show = () => {
        dlg.showModal();
        root.classList.add("viewer-open");
        isOpen = true;
        go(i, false);
        render(i);
      };
      const tImg = from?.querySelector("img");
      if (canMorph() && tImg) {
        tImg.style.viewTransitionName = "photo";
        const vt = document.startViewTransition(() => {
          tImg.style.viewTransitionName = "";
          show();
          target.style.viewTransitionName = "photo";
        });
        vt.finished.finally(() => { target.style.viewTransitionName = ""; });
      } else {
        show();
      }
    }

    function finishClose() {
      dlg.close();
      root.classList.remove("viewer-open", "is-dragging");
      dlg.classList.remove("ui-hidden", "dragging");
      dlg.style.removeProperty("--bg-a");
      for (const im of track.querySelectorAll("img")) im.style.transform = "";
      isOpen = false;
    }

    // Closing always goes through history, so the Back button and the ✕ behave the same.
    function close() {
      if (!isOpen) return;
      const im = slideImg(index), tImg = thumbImg(index);
      if (canMorph() && im && tImg) {
        im.style.viewTransitionName = "photo";
        const vt = document.startViewTransition(() => {
          im.style.viewTransitionName = "";
          finishClose();
          const r = tImg.getBoundingClientRect();
          if (r.bottom < 0 || r.top > innerHeight) tImg.scrollIntoView({ block: "center" });
          tImg.style.viewTransitionName = "photo";
        });
        vt.finished.finally(() => { tImg.style.viewTransitionName = ""; });
      } else {
        finishClose();
      }
    }
    const requestClose = () => { if (history.state?.viewer) history.back(); else { close(); history.replaceState(null, "", location.pathname + location.search); } };

    addEventListener("popstate", () => {
      const m = location.hash.match(/^#(\d+)$/);
      if (isOpen && !m) close();
      else if (!isOpen && m) open(Number(m[1]) - 1, { push: false });
    });

    for (const a of thumbs) {
      a.addEventListener("click", e => {
        if (e.defaultPrevented || e.button !== 0 || e.metaKey || e.ctrlKey || e.shiftKey || e.altKey) return;
        e.preventDefault();
        open(Number(a.dataset.i), { from: a });
      });
    }

    dlg.addEventListener("cancel", e => { e.preventDefault(); requestClose(); });
    // If the browser force-closes the dialog (e.g. repeated Esc), still clean up state and history.
    dlg.addEventListener("close", () => {
      if (!isOpen) return;
      isOpen = false;
      root.classList.remove("viewer-open");
      if (history.state?.viewer) history.back();
    });
    dlg.querySelector(".v-close").addEventListener("click", requestClose);
    prevBtn?.addEventListener("click", () => go(index - 1));
    nextBtn?.addEventListener("click", () => go(index + 1));
    dlg.addEventListener("keydown", e => {
      if (e.key === "ArrowRight") { e.preventDefault(); go(index + 1); }
      else if (e.key === "ArrowLeft") { e.preventDefault(); go(index - 1); }
    });

    dlg.querySelector(".v-share")?.addEventListener("click", async () => {
      const url = location.href;
      try {
        if (navigator.share) { await navigator.share({ title: document.title, url }); return; }
        await navigator.clipboard.writeText(url);
        toast.textContent = "Link copied";
      } catch (_) {
        return;
      }
      toast.classList.add("on");
      setTimeout(() => toast.classList.remove("on"), 1600);
    });

    // Gestures on the photo: tap toggles the bars (touch), click halves navigate (mouse),
    // a vertical drag follows the finger and dismisses past a distance or speed threshold.
    let ptr = null;
    const rubber = (x, d = 300, c = .55) => (x * d * c) / (d + c * Math.abs(x));
    track.addEventListener("pointerdown", e => {
      if (!isOpen || e.button !== 0) return;
      if (window.visualViewport && visualViewport.scale > 1.01) return; // pinch-zoomed: leave it to the browser
      const now = performance.now();
      ptr = { id: e.pointerId, type: e.pointerType, x0: e.clientX, y0: e.clientY, t0: now, y: e.clientY, t: now, vy: 0, mode: null };
    });
    track.addEventListener("pointermove", e => {
      if (!ptr || e.pointerId !== ptr.id) return;
      const dx = e.clientX - ptr.x0, dy = e.clientY - ptr.y0;
      if (!ptr.mode) {
        if (Math.abs(dy) > 10 && Math.abs(dy) > Math.abs(dx) * 1.2) {
          ptr.mode = "dismiss";
          try { track.setPointerCapture(e.pointerId); } catch (_) { /* already released */ }
          dlg.classList.add("dragging");
        } else if (Math.abs(dx) > 10) {
          ptr.mode = "pan";
        }
      }
      if (ptr.mode !== "dismiss") return;
      const now = performance.now();
      ptr.vy = (e.clientY - ptr.y) / Math.max(1, now - ptr.t);
      ptr.y = e.clientY; ptr.t = now;
      const y = dy > 0 ? dy : rubber(dy);
      const p = Math.min(1, Math.max(0, y) / 400);
      const im = slideImg(index);
      if (im) im.style.transform = `translate(${dx * .4}px, ${y}px) scale(${1 - p * .25})`;
      dlg.style.setProperty("--bg-a", String(1 - p * .9));
    });
    const endPointer = e => {
      if (!ptr || e.pointerId !== ptr.id) return;
      const dx = e.clientX - ptr.x0, dy = e.clientY - ptr.y0, dt = performance.now() - ptr.t0;
      const mode = ptr.mode, vy = ptr.vy, type = ptr.type;
      ptr = null;
      if (mode === "dismiss") {
        if (e.type !== "pointercancel" && (dy > 120 || vy > .6)) { requestClose(); return; }
        springBack();
        return;
      }
      if (!mode && e.type === "pointerup" && Math.hypot(dx, dy) < 8 && dt < 350) {
        if (type === "mouse") {
          const r = track.getBoundingClientRect();
          go(index + (e.clientX > r.left + r.width / 2 ? 1 : -1));
        } else {
          dlg.classList.toggle("ui-hidden");
        }
      }
    };
    track.addEventListener("pointerup", endPointer);
    track.addEventListener("pointercancel", endPointer);

    function springBack() {
      dlg.classList.remove("dragging");
      const im = slideImg(index);
      const from = im?.style.transform;
      if (im) {
        im.style.transform = "";
        if (from && !reduceMotion.matches) {
          const frames = [{ transform: from }, { transform: "none" }];
          try { im.animate(frames, { duration: 450, easing: getComputedStyle(root).getPropertyValue("--spring").trim() }); }
          catch (_) { im.animate(frames, { duration: 300, easing: "ease-out" }); }
        }
      }
      dlg.style.removeProperty("--bg-a");
    }

    // Deep link: /work/<slug>/#3 opens photo 3; Back then closes it instead of leaving the page.
    const m = location.hash.match(/^#(\d+)$/);
    if (m) {
      const i = Number(m[1]) - 1;
      if (i >= 0 && i < photos.length) {
        history.replaceState(null, "", location.pathname + location.search);
        open(i);
      }
    }
  }
})();
